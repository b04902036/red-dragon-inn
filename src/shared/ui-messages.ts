export interface UiMessage {
  key: MessageKey;
  values?: Record<string, string | number>;
}
export const uiMessage = (
  key: MessageKey,
  values?: UiMessage['values'],
): UiMessage => ({ key, ...(values ? { values } : {}) });
export function formatMessage(
  locale: Locale,
  key: MessageKey,
  values: UiMessage['values'] = {},
) {
  const resolved = { ...values };
  for (const field of key === 'log.stat'
    ? ['stat']
    : key === 'log.phase' || key === 'log.phasePlayer'
      ? ['phase']
      : []) {
    const nested = resolved[field];
    if (typeof nested === 'string' && Object.hasOwn(englishMessages, nested))
      resolved[field] = formatMessage(locale, nested as MessageKey);
  }
  const text =
    locale === 'zh-TW' ? traditionalChineseMessages[key] : englishMessages[key];
  return text.replace(/\{([a-zA-Z]+)\}/g, (placeholder, parameter: string) =>
    String(resolved[parameter] ?? placeholder),
  );
}
