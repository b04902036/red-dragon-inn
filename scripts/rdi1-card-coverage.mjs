import { readFile, writeFile } from 'node:fs/promises';
import { format } from 'prettier';

const source = JSON.parse(
  await readFile('content-private/imports/rdi1/source-normalized.json', 'utf8'),
);
const pack = JSON.parse(
  await readFile(
    source.contentVersion
      ? `content-private/imports/rdi1/pack-${source.contentVersion.id}.json`
      : 'content-private/imports/rdi1/pack.json',
    'utf8',
  ),
);
const records = [
  ...source.characters.flatMap((character) =>
    character.cards.map((card) => ({
      id: `carddef_rdi1_${card.cardKey.replaceAll('.', '_').replaceAll('-', '_')}`,
      deck: character.id,
      quantity: card.quantity,
      mechanic: card.mechanicId,
    })),
  ),
  ...source.drinkDeck.cards.map((card) => ({
    id: `carddef_rdi1_drink_${card.drinkKey}`,
    deck: 'drink',
    quantity: card.quantity,
    mechanic: card.drinkKey,
  })),
];
if (
  records.length !== pack.cards.length ||
  new Set(records.map((r) => r.id)).size !== records.length
)
  throw new Error('Coverage graph does not match compiled definitions');
const cell = (value) =>
  String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
const lines = [
  '# RDI1 per-card coverage',
  '',
  'Generated by `npm run content:coverage:rdi1` from the locked normalized input and compiled pack. Each test is parameterized by the exact definition ID below; repeated physical copies share that verified definition. No private card prose or artwork is included.',
  '',
  '110 definitions; 160 character copies (40 each for Deirdre, Fiona, Gerki and Zot); 30 Drink copies. Tests use the actual compiled effects and structured legality. The table records English/Traditional Chinese translation presence, not a new translation review.',
  '',
  'Sometimes: every definition has positive server `legalPlays`, private 30-second prompt, pass/timeout/reconnect/replay, negative ordinary-context command rejection, compiled effect resolution and stale prompt/version rejection. The client suite renders each definition through GameTable and checks its server highlight and English MP3 deduplication. Anytime: every definition is checked during ordinary, source response, gambling and 15-second grace opportunities; Anytime-only 30-second responses remain silent.',
  '',
  'Four-browser production verification uses a separate test Worker entry with invariant-checked checkpoints and an injected clock/shortened alarm deadline. D1 commands replay from each checkpoint to identical state, including the final winner. The published edition, game definitions, hibernating WebSockets, session validation, projections and command handlers remain production implementations. Test routes are absent from the production entry and build.',
  '',
  '| Definition / deck | Quantity | Type | Mechanic | Legal timing | Response trigger | Effect handler / DSL | en-US | zh-TW | Positive legality test | Negative legality test | Effect-resolution test |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
];
for (const record of records.sort((a, b) => a.id.localeCompare(b.id))) {
  const card = pack.cards.find((c) => c.id === record.id);
  if (!card) throw new Error(`Missing definition ${record.id}`);
  const drink = card.type === 'DRINK' || card.type === 'DRINK_EVENT';
  const file = drink
    ? 'rdi1-drinks.test.ts'
    : card.type === 'SOMETIMES' || card.type === 'ANYTIME'
      ? 'rdi1-per-card.test.ts'
      : 'rdi1-actions-gambling.test.ts';
  const test = (label) => `[${label}: ${record.id}](../tests/engine/${file})`;
  const timing = drink
    ? 'DRINK / forced/batch reveal'
    : card.type === 'ANYTIME'
      ? 'ordinary; source/system responses; gambling; phase-end 15s'
      : card.type === 'SOMETIMES'
        ? (card.phaseOpportunity ?? 'matching source/system response (30s)')
        : card.type === 'ACTION'
          ? 'active Action phase'
          : card.gambling?.canStart
            ? 'active Action; Gambling priority'
            : 'Gambling priority / control restrictions';
  const translations = (locale) =>
    ['name', 'rulesText'].every((field) =>
      pack.translations.some(
        (t) =>
          t.entityType === 'CARD' &&
          t.entityId === card.id &&
          t.field === field &&
          t.locale === locale &&
          t.text.trim(),
      ),
    )
      ? 'present'
      : 'MISSING';
  const effects =
    card.type === 'DRINK'
      ? `numeric Alcohol ${card.alcoholContent}; Fortitude ${card.fortitudeChange}; chaser ${card.chaser}; traits ${JSON.stringify(card.traitReplacements ?? [])}`
      : JSON.stringify(card.effects);
  const columns = [
    `\`${record.id}\` / ${record.deck}`,
    record.quantity,
    card.type,
    `\`${record.mechanic}\``,
    timing,
    card.responseTrigger
      ? `\`${JSON.stringify(card.responseTrigger)}\``
      : 'none',
    `\`${effects}\``,
    translations('en-US'),
    translations('zh-TW'),
    test('positive'),
    test('negative'),
    test('resolution'),
  ];
  if (columns.includes('MISSING'))
    throw new Error(`Missing translation ${card.id}`);
  lines.push(`| ${columns.map(cell).join(' | ')} |`);
}
const rendered = await format(lines.join('\n') + '\n', { parser: 'markdown' });
const output = 'docs/rdi1-card-coverage.md';
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== rendered)
    throw new Error('Regenerate the RDI1 coverage matrix');
} else await writeFile(output, rendered);
console.log(
  'RDI1 coverage matrix: 110/110 definitions, 160/160 character copies, 30/30 Drink copies, both locales present.',
);
